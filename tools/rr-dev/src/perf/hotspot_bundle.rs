//! Native hotspot bundle export and instruction aggregation.
//!
//! Rust owns the input path, capture identity, `IDALib` isolation, output schema,
//! sample mapping gates, checksums, failure state and publication. `IDALib` exposes
//! its automation API through Python, so the only Python retained here is a
//! generated private bridge containing direct IDA API calls. It has no argument,
//! path, identity, verdict or publication policy of its own.

