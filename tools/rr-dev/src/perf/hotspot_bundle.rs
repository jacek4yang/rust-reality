fn aggregate(
    output: &RunDirectory,
    function: &mut Function,
    samples: &[Sample],
    selection_totals: &SelectionTotals,
    capture: &Capture,
    expected_dso_path: &str,
    plan: &Plan,
) -> Result<(Totals, f64), String> {
    let expected_dso = dso_basename(expected_dso_path)
        .ok_or_else(|| "perf DSO path has no UTF-8 basename".to_owned())?;
    let totals = map_samples(function, samples)?;
    let unmapped_percent = totals.unmapped_period as f64 * 100.0 / totals.period_sum as f64;
    if unmapped_percent >= HARD_UNMAPPED_PERCENT {
        return Err(format!(
            "unmapped perf period {unmapped_percent:.6}% is not below the 1% hard gate"
        ));
    }
    if unmapped_percent > plan.max_unmapped_period_percent {
        return Err(format!(
            "unmapped perf period {unmapped_percent:.6}% exceeds the reviewed {:.6}% gate",
            plan.max_unmapped_period_percent
        ));
    }
    let mut ranked_instructions = function
        .instructions
        .iter()
        .filter(|instruction| instruction.sample_count > 0)
        .collect::<Vec<_>>();
    ranked_instructions.sort_by(|left, right| sampled_order(left, right));

    let instruction_rows = ranked_instructions
        .iter()
        .enumerate()
        .map(|(index, instruction)| {
            let Json::Object(mut row) = instruction_json(instruction, function.start)? else {
                unreachable!("instruction JSON is an object");
            };
            row.insert(
                "rank".to_owned(),
                json_u64(
                    u64::try_from(index + 1).map_err(|error| error.to_string())?,
                    "rank",
                )?,
            );
            row.insert(
                "samplePercent".to_owned(),
                Json::Float(instruction.sample_count as f64 * 100.0 / totals.mapped_rows as f64),
            );
            row.insert(
                "periodPercent".to_owned(),
                Json::Float(instruction.period_sum as f64 * 100.0 / totals.mapped_period as f64),
            );
            Ok(Json::Object(row))
        })
        .collect::<Result<Vec<_>, String>>()?;
    let explanation = plan
        .unmapped_period_explanation
        .as_deref()
        .map_or(Json::Null, Json::string);
    let report = Json::object([
        ("schemaVersion", Json::Int(3)),
        (
            "identity",
            Json::object([
                ("binary_sha256", Json::string(&capture.binary_sha256)),
                ("binary_build_id", Json::string(&capture.binary_build_id)),
                ("ida_function_name", Json::string(&function.name)),
                ("dso_basename", Json::string(expected_dso)),
                ("perf_dso_path", Json::string(expected_dso_path)),
                (
                    "address_normalization",
                    Json::string("perf-dso-file-offset-through-executable-elf-pt-load"),
                ),
            ]),
        ),
        (
            "mappingGate",
            Json::object([
                (
                    "maxUnmappedPeriodPercent",
                    Json::Float(plan.max_unmapped_period_percent),
                ),
                (
                    "hardMaximumPercentExclusive",
                    Json::Float(HARD_UNMAPPED_PERCENT),
                ),
                ("unmappedPeriodExplanation", explanation),
            ]),
        ),
        (
            "function",
            Json::object([
                ("name", Json::string(&function.name)),
                ("start", Json::string(format!("0x{:x}", function.start))),
                ("end", Json::string(format!("0x{:x}", function.end))),
                (
                    "size",
                    json_u64(function.end - function.start, "function size")?,
                ),
                (
                    "instructionCount",
                    json_u64(
                        u64::try_from(function.instructions.len())
                            .map_err(|error| error.to_string())?,
                        "instruction count",
                    )?,
                ),
                (
                    "sampledInstructionCount",
                    json_u64(
                        u64::try_from(ranked_instructions.len())
                            .map_err(|error| error.to_string())?,
                        "sampled instruction count",
                    )?,
                ),
            ]),
        ),
        ("selectionTotals", selection_totals_json(selection_totals)?),
        ("totals", totals_json(&totals, unmapped_percent)?),
        ("instructions", Json::Array(instruction_rows)),
    ]);
    output.write_new("instruction-hotspots.json", &report.to_python_json())?;

    let mut tsv = String::from(
        "rank\tperiod_percent\tsample_percent\tperiod_sum\tsample_count\taddress\toffset\tsize\tbytes\tinstruction\n",
    );
    for (index, instruction) in ranked_instructions.iter().enumerate() {
        let text = instruction.text.replace('\t', " ");
        let _ = writeln!(
            tsv,
            "{}\t{:.6}\t{:.6}\t{}\t{}\t0x{:x}\t0x{:x}\t{}\t{}\t{}",
            index + 1,
            instruction.period_sum as f64 * 100.0 / totals.mapped_period as f64,
            instruction.sample_count as f64 * 100.0 / totals.mapped_rows as f64,
            instruction.period_sum,
            instruction.sample_count,
            instruction.address,
            instruction.address - function.start,
            instruction.size,
            instruction.bytes,
            text
        );
    }
    output.write_new("instruction-hotspots.tsv", &tsv)?;

    let mut text = format!(
        "Function: {}\nSamples: {}/{} mapped\nUnmapped period: {:.6}%\n\nRank  Period%  Samples  Address     Offset   Instruction\n",
        function.name, totals.mapped_rows, totals.sample_rows, unmapped_percent
    );
    for (index, instruction) in ranked_instructions.iter().take(40).enumerate() {
        let _ = writeln!(
            text,
            "{:>4}  {:>7.3}  {:>7}  {:>10}  {:>7}  {}",
            index + 1,
            instruction.period_sum as f64 * 100.0 / totals.mapped_period as f64,
            instruction.sample_count,
            format!("0x{:x}", instruction.address),
            format!("0x{:x}", instruction.address - function.start),
            instruction.text
        );
    }
    output.write_new("instruction-hotspots.txt", &text)?;
    Ok((totals, unmapped_percent))
}

