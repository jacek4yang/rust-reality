fn read_array<const N: usize>(
    bytes: &[u8],
    offset: usize,
    context: &str,
) -> Result<[u8; N], String> {
    let end = offset
        .checked_add(N)
        .ok_or_else(|| format!("{context} offset overflow"))?;
    bytes
        .get(offset..end)
        .ok_or_else(|| format!("truncated {context}"))?
        .try_into()
        .map_err(|_| format!("invalid {context}"))
}

fn elf_u16(bytes: &[u8], offset: usize, context: &str) -> Result<u16, String> {
    Ok(u16::from_le_bytes(read_array(bytes, offset, context)?))
}

fn elf_u32(bytes: &[u8], offset: usize, context: &str) -> Result<u32, String> {
    Ok(u32::from_le_bytes(read_array(bytes, offset, context)?))
}

fn elf_u64(bytes: &[u8], offset: usize, context: &str) -> Result<u64, String> {
    Ok(u64::from_le_bytes(read_array(bytes, offset, context)?))
}

impl ElfAddressMap {
    fn parse(binary: &Path) -> Result<Self, String> {
        let bytes = std::fs::read(binary)
            .map_err(|error| format!("could not read ELF {}: {error}", binary.display()))?;
        if bytes.get(..4) != Some(b"\x7fELF")
            || bytes.get(4) != Some(&2)
            || bytes.get(5) != Some(&1)
            || bytes.get(6) != Some(&1)
        {
            return Err("hotspot bundle requires a little-endian ELF64 binary".to_owned());
        }
        let elf_type = elf_u16(&bytes, 16, "ELF type")?;
        let machine = elf_u16(&bytes, 18, "ELF machine")?;
        if !matches!(elf_type, 2 | 3) || machine != 62 || elf_u32(&bytes, 20, "ELF version")? != 1 {
            return Err("hotspot bundle requires an x86-64 ET_EXEC or ET_DYN ELF".to_owned());
        }
        let program_offset = elf_u64(&bytes, 32, "program-header table offset")?;
        let header_size = elf_u16(&bytes, 52, "ELF header size")?;
        let entry_size = elf_u16(&bytes, 54, "program-header entry size")?;
        let entry_count = elf_u16(&bytes, 56, "program-header entry count")?;
        if header_size < 64 || entry_size < 56 || entry_count == 0 || entry_count == u16::MAX {
            return Err("ELF program-header table is unsupported or empty".to_owned());
        }
        let program_offset = usize::try_from(program_offset)
            .map_err(|_| "ELF program-header offset exceeds addressable memory".to_owned())?;
        let entry_size = usize::from(entry_size);
        let mut loads = Vec::new();
        for index in 0..usize::from(entry_count) {
            let offset = index
                .checked_mul(entry_size)
                .and_then(|value| program_offset.checked_add(value))
                .ok_or_else(|| "ELF program-header offset overflow".to_owned())?;
            let entry_end = offset
                .checked_add(entry_size)
                .ok_or_else(|| "ELF program-header range overflow".to_owned())?;
            let entry = bytes
                .get(offset..entry_end)
                .ok_or_else(|| "truncated ELF program-header table".to_owned())?;
            if elf_u32(entry, 0, "program-header type")? != 1 {
                continue;
            }
            let segment = LoadSegment {
                flags: elf_u32(entry, 4, "PT_LOAD flags")?,
                file_offset: elf_u64(entry, 8, "PT_LOAD file offset")?,
                virtual_address: elf_u64(entry, 16, "PT_LOAD virtual address")?,
                file_size: elf_u64(entry, 32, "PT_LOAD file size")?,
                memory_size: elf_u64(entry, 40, "PT_LOAD memory size")?,
                alignment: elf_u64(entry, 48, "PT_LOAD alignment")?,
            };
            let file_end = segment
                .file_offset
                .checked_add(segment.file_size)
                .ok_or_else(|| "PT_LOAD file range overflow".to_owned())?;
            let memory_end = segment
                .virtual_address
                .checked_add(segment.memory_size)
                .ok_or_else(|| "PT_LOAD memory range overflow".to_owned())?;
            if segment.file_size > segment.memory_size
                || file_end > u64::try_from(bytes.len()).map_err(|error| error.to_string())?
                || memory_end < segment.virtual_address
                || (segment.alignment > 1
                    && (!segment.alignment.is_power_of_two()
                        || segment.file_offset % segment.alignment
                            != segment.virtual_address % segment.alignment))
            {
                return Err("ELF contains an invalid PT_LOAD range".to_owned());
            }
            loads.push(segment);
        }
        if !loads
            .iter()
            .any(|segment| segment.executable() && segment.file_size > 0)
        {
            return Err("ELF has no file-backed executable PT_LOAD segment".to_owned());
        }
        Ok(Self { loads })
    }

    fn dso_offset_to_static(&self, dso_offset: u64) -> Result<u64, String> {
        let matches = self
            .loads
            .iter()
            .filter(|segment| {
                segment.executable()
                    && dso_offset >= segment.file_offset
                    && dso_offset - segment.file_offset < segment.file_size
            })
            .collect::<Vec<_>>();
        let [segment] = matches.as_slice() else {
            return Err(format!(
                "perf DSO offset 0x{dso_offset:x} is not in exactly one file-backed executable PT_LOAD"
            ));
        };
        segment
            .virtual_address
            .checked_add(dso_offset - segment.file_offset)
            .ok_or_else(|| "static ELF address overflow".to_owned())
    }

    fn static_to_dso_offset(&self, address: u64) -> Result<u64, String> {
        let matches = self
            .loads
            .iter()
            .filter(|segment| {
                segment.executable()
                    && address >= segment.virtual_address
                    && address - segment.virtual_address < segment.file_size
            })
            .collect::<Vec<_>>();
        let [segment] = matches.as_slice() else {
            return Err(format!(
                "static ELF address 0x{address:x} is not in exactly one file-backed executable PT_LOAD"
            ));
        };
        segment
            .file_offset
            .checked_add(address - segment.virtual_address)
            .ok_or_else(|| "perf DSO offset overflow".to_owned())
    }
}

fn safe_component(value: &str) -> bool {
    let mut bytes = value.bytes();
    bytes
        .next()
        .is_some_and(|byte| byte.is_ascii_alphanumeric())
        && value.len() <= 96
        && bytes.all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-'))
}

fn parse_address(value: &str, context: &str) -> Result<u64, String> {
    let digits = value
        .strip_prefix("0x")
        .or_else(|| value.strip_prefix("0X"))
        .ok_or_else(|| format!("{context} must be hexadecimal with a 0x prefix"))?;
    if digits.is_empty() || !digits.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return Err(format!("{context} must be hexadecimal with a 0x prefix"));
    }
    u64::from_str_radix(digits, 16).map_err(|error| format!("invalid {context}: {error}"))
}

fn valid_lower_hex(value: &str, length: Option<usize>) -> bool {
    length.is_none_or(|expected| value.len() == expected)
        && !value.is_empty()
        && value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}

fn regular_not_symlink(path: &Path, context: &str) -> Result<(), String> {
    let metadata = path
        .symlink_metadata()
        .map_err(|error| format!("could not stat {context} {}: {error}", path.display()))?;
    if metadata.file_type().is_symlink() || !metadata.is_file() {
        return Err(format!(
            "{context} is not a regular non-symlink file: {}",
            path.display()
        ));
    }
    Ok(())
}

/// Validates bounded arguments without invoking `IDALib` or perf.
///
/// # Errors
///
/// Returns one actionable argument diagnostic.
pub fn validate(plan: &Plan) -> Result<(), String> {
    if !plan.run_dir.is_absolute() {
        return Err("--run-dir must be absolute".to_owned());
    }
    if !safe_component(&plan.label) {
        return Err("--label must be a 1..=96 character safe identifier".to_owned());
    }
    parse_address(&plan.dso_offset, "--dso-offset")?;
    if !plan.idalib_python.is_absolute() {
        return Err("--idalib-python must be absolute".to_owned());
    }
    regular_not_symlink(&plan.idalib_python, "IDALib Python")?;
    let mode = plan
        .idalib_python
        .metadata()
        .map_err(|error| format!("could not stat IDALib Python: {error}"))?
        .permissions()
        .mode();
    if mode & 0o111 == 0 {
        return Err("--idalib-python must be executable".to_owned());
    }
    if plan.timeout_seconds == 0 || plan.timeout_seconds > MAX_TIMEOUT_SECONDS {
        return Err("--timeout-seconds must be in 1..=1800".to_owned());
    }
    if !plan.max_unmapped_period_percent.is_finite()
        || !(0.0..HARD_UNMAPPED_PERCENT).contains(&plan.max_unmapped_period_percent)
    {
        return Err("--max-unmapped-period-percent must be in [0, 1)".to_owned());
    }
    match (
        plan.max_unmapped_period_percent > 0.0,
        plan.unmapped_period_explanation
            .as_deref()
            .is_some_and(|value| !value.trim().is_empty()),
    ) {
        (true, false) => {
            return Err(
                "a non-zero mapping threshold requires --unmapped-period-explanation".to_owned(),
            );
        }
        (false, true) => {
            return Err("an unmapped-period explanation requires a non-zero threshold".to_owned());
        }
        _ => {}
    }
    Ok(())
}

fn read_json(path: &Path, context: &str) -> Result<json_in::Value, String> {
    read_json_snapshot(path, context).map(|(value, _)| value)
}

fn read_json_snapshot(
    path: &Path,
    context: &str,
) -> Result<(json_in::Value, String), String> {
    let bytes = std::fs::read(path)
        .map_err(|error| format!("could not read {context} {}: {error}", path.display()))?;
    let text = std::str::from_utf8(&bytes)
        .map_err(|error| format!("invalid UTF-8 in {context} {}: {error}", path.display()))?;
    let value = json_in::parse(text)
        .map_err(|error| format!("invalid {context} {}: {error}", path.display()))?;
    Ok((value, crate::perf::loader::sha256_bytes(&bytes)))
}

fn load_capture(plan: &Plan) -> Result<Capture, String> {
    let root_metadata = plan.run_dir.symlink_metadata().map_err(|error| {
        format!(
            "could not stat --run-dir {}: {error}",
            plan.run_dir.display()
        )
    })?;
    if root_metadata.file_type().is_symlink() || !root_metadata.is_dir() {
        return Err("--run-dir must be an existing non-symlink directory".to_owned());
    }
    let root = plan
        .run_dir
        .canonicalize()
        .map_err(|error| format!("could not canonicalize --run-dir: {error}"))?;
    let metadata_path = root.join("metadata.json");
    let completion_path = root.join("run-completion.json");
    let contract_path = root.join("run-contract.json");
    let perf_data = root.join("perf.data");
    for (path, context) in [
        (&metadata_path, "hotspot metadata"),
        (&completion_path, "hotspot completion"),
        (&contract_path, "hotspot contract"),
        (&perf_data, "perf data"),
    ] {
        regular_not_symlink(path, context)?;
    }
    let (contract, contract_sha256) = read_json_snapshot(&contract_path, "hotspot contract")?;
    contract
        .require_int("hotspot contract", "schemaVersion", 2)
        .map_err(|_| {
            "hotspot contract is not hash-bound to perf.data; recapture with the current rr-dev"
                .to_owned()
        })?;
    contract
        .require_str("hotspot contract", "collector", "perf-hotspot")
        .map_err(|error| error.to_string())?;
    contract
        .require_str("hotspot contract", "phase", "complete")
        .map_err(|error| error.to_string())?;
    contract
        .require_int("hotspot contract", "exitCode", 0)
        .map_err(|error| error.to_string())?;
    let run_id = contract
        .str_field("hotspot contract", "runId")
        .map_err(|error| error.to_string())?
        .to_owned();
    if run_id.is_empty() {
        return Err("hotspot contract run ID is empty".to_owned());
    }
    let contract_binary = contract
        .field("hotspot contract", "binary")
        .map_err(|error| error.to_string())?;
    let binary_sha256 = contract_binary
        .str_field("hotspot contract.binary", "sha256")
        .map_err(|error| error.to_string())?
        .to_owned();
    let binary_build_id = contract_binary
        .str_field("hotspot contract.binary", "buildId")
        .map_err(|error| error.to_string())?
        .to_owned();
    if !valid_lower_hex(&binary_sha256, Some(64)) || !valid_lower_hex(&binary_build_id, None) {
        return Err("hotspot contract binary identity is malformed".to_owned());
    }
    let contract_perf_data = contract.optional("perfData").ok_or_else(|| {
        "hotspot contract does not bind perf.data; recapture with the current rr-dev".to_owned()
    })?;
    contract_perf_data
        .require_str("hotspot contract.perfData", "relativePath", "perf.data")
        .map_err(|error| error.to_string())?;
    let perf_data_sha256 = contract_perf_data
        .str_field("hotspot contract.perfData", "sha256")
        .map_err(|error| error.to_string())?
        .to_owned();
    if !valid_lower_hex(&perf_data_sha256, Some(64)) {
        return Err("hotspot contract perf.data identity is malformed".to_owned());
    }
    let completion = read_json(&completion_path, "hotspot completion")?;
    crate::perf::loader::verify_success_marker(
        &completion,
        &contract_path,
        &contract_sha256,
        &run_id,
        "perf-hotspot",
        "hotspot completion",
    )
    .map_err(|error| error.to_string())?;

    let metadata = read_json(&metadata_path, "hotspot metadata")?;
    metadata
        .require_str("metadata", "state", "COMPLETE")
        .map_err(|error| error.to_string())?;
    if metadata
        .str_field("metadata", "runId")
        .map_err(|error| error.to_string())?
        != run_id
        || metadata
            .str_field("metadata", "binarySha256")
            .map_err(|error| error.to_string())?
            != binary_sha256
        || metadata
            .str_field("metadata", "binaryBuildId")
            .map_err(|error| error.to_string())?
            != binary_build_id
    {
        return Err("hotspot metadata disagrees with the bound capture contract".to_owned());
    }

    let binary_dir = root.join("binary");
    let entries = std::fs::read_dir(&binary_dir)
        .map_err(|error| format!("could not read {}: {error}", binary_dir.display()))?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|error| format!("could not enumerate {}: {error}", binary_dir.display()))?;
    if entries.len() != 1 {
        return Err(format!(
            "hotspot capture must contain exactly one archived binary, found {}",
            entries.len()
        ));
    }
    let binary = entries[0].path();
    regular_not_symlink(&binary, "archived binary")?;
    if hash::sha256_file(&binary)? != binary_sha256 {
        return Err("archived binary SHA-256 does not match completed capture".to_owned());
    }
    if attest::build_id(&binary)? != binary_build_id {
        return Err("archived binary Build ID does not match completed capture".to_owned());
    }
    let perf_bytes = perf_data
        .metadata()
        .map_err(|error| format!("could not stat perf data: {error}"))?
        .len();
    if perf_bytes == 0 || perf_bytes > MAX_PERF_DATA_BYTES {
        return Err("perf data must be non-empty and no larger than 1 GiB".to_owned());
    }
    if hash::sha256_file(&perf_data)? != perf_data_sha256 {
        return Err("perf data SHA-256 does not match completed capture".to_owned());
    }
    Ok(Capture {
        root,
        run_id,
        binary,
        binary_sha256,
        binary_build_id,
        perf_data,
        perf_data_sha256,
    })
}

fn write_new(path: &Path, contents: &[u8]) -> Result<(), String> {
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
        .map_err(|error| format!("could not create {}: {error}", path.display()))?;
    file.write_all(contents)
        .map_err(|error| format!("could not write {}: {error}", path.display()))?;
    file.sync_all()
        .map_err(|error| format!("could not sync {}: {error}", path.display()))
}

fn run_stdout_file(
    program: &Path,
    args: &[String],
    stdout: &Path,
    stderr: &Path,
) -> Result<(), String> {
    let stdout_file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(stdout)
        .map_err(|error| format!("could not create {}: {error}", stdout.display()))?;
    let stderr_file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(stderr)
        .map_err(|error| format!("could not create {}: {error}", stderr.display()))?;
    let status = Command::new(program)
        .args(args)
        .stdin(Stdio::null())
        .stdout(Stdio::from(stdout_file))
        .stderr(Stdio::from(stderr_file))
        .status()
        .map_err(|error| format!("could not run {}: {error}", program.display()))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!(
            "{} failed with {}; see {}",
            program.display(),
            status,
            stderr.display()
        ))
    }
}

fn json_u64(value: u64, context: &str) -> Result<Json, String> {
    i64::try_from(value)
        .map(Json::Int)
        .map_err(|_| format!("{context} exceeds the JSON integer range"))
}

fn parse_idalib_result(path: &Path, requested: u64) -> Result<Function, String> {
    let result = read_json(path, "IDALib bridge result")?;
    let observed_requested = parse_address(
        result
            .str_field("idalib", "requestedAddress")
            .map_err(|error| error.to_string())?,
        "IDALib requestedAddress",
    )?;
    if observed_requested != requested {
        return Err("IDALib returned a different requested address".to_owned());
    }
    let function = result
        .field("idalib", "function")
        .map_err(|error| error.to_string())?;
    let name = function
        .str_field("idalib.function", "name")
        .map_err(|error| error.to_string())?
        .to_owned();
    if name.is_empty() {
        return Err("IDALib returned an empty function name".to_owned());
    }
    let start = parse_address(
        function
            .str_field("idalib.function", "start")
            .map_err(|error| error.to_string())?,
        "IDALib function start",
    )?;
    let end = parse_address(
        function
            .str_field("idalib.function", "end")
            .map_err(|error| error.to_string())?,
        "IDALib function end",
    )?;
    if end <= start || requested < start || requested >= end || end - start > MAX_FUNCTION_BYTES {
        return Err("IDALib returned an invalid or oversized function range".to_owned());
    }
    let raw_instructions = result
        .array_field("idalib", "instructions")
        .map_err(|error| error.to_string())?;
    if raw_instructions.is_empty() || raw_instructions.len() > MAX_INSTRUCTIONS {
        return Err("IDALib returned an empty or oversized instruction list".to_owned());
    }
    let mut instructions = Vec::with_capacity(raw_instructions.len());
    for (index, raw) in raw_instructions.iter().enumerate() {
        let context = format!("idalib.instructions[{index}]");
        let address = parse_address(
            raw.str_field(&context, "address")
                .map_err(|error| error.to_string())?,
            &format!("{context}.address"),
        )?;
        let size = u64::try_from(
            raw.int_field(&context, "size")
                .map_err(|error| error.to_string())?,
        )
        .map_err(|_| format!("{context}.size must be positive"))?;
        let bytes = raw
            .str_field(&context, "bytes")
            .map_err(|error| error.to_string())?
            .to_owned();
        let text = raw
            .str_field(&context, "text")
            .map_err(|error| error.to_string())?
            .to_owned();
        let byte_length = usize::try_from(size)
            .ok()
            .and_then(|value| value.checked_mul(2));
        if size == 0
            || address < start
            || address >= end
            || address.checked_add(size).is_none_or(|last| last > end)
            || Some(bytes.len()) != byte_length
            || !bytes.bytes().all(|byte| byte.is_ascii_hexdigit())
        {
            return Err(format!("invalid IDALib instruction at index {index}"));
        }
        instructions.push(Instruction {
            address,
            size,
            bytes,
            text,
            sample_count: 0,
            period_sum: 0,
        });
    }
    instructions.sort_by_key(|instruction| instruction.address);
    for pair in instructions.windows(2) {
        if pair[0].address + pair[0].size > pair[1].address {
            return Err("IDALib instruction ranges overlap".to_owned());
        }
    }
    let pseudocode = result
        .str_field("idalib", "pseudocode")
        .map_err(|error| error.to_string())?
        .to_owned();
    if pseudocode.trim().is_empty() {
        return Err("IDALib returned empty pseudocode".to_owned());
    }
    Ok(Function {
        name,
        start,
        end,
        instructions,
        pseudocode,
    })
}

