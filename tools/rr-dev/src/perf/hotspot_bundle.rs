fn execute(plan: &Plan, capture: &Capture, output: &RunDirectory) -> Result<(), String> {
    let requested_dso_offset = parse_address(&plan.dso_offset, "--dso-offset")?;
    let address_map = ElfAddressMap::parse(&capture.binary)?;
    let requested = address_map.dso_offset_to_static(requested_dso_offset)?;
    if address_map.static_to_dso_offset(requested)? != requested_dso_offset {
        return Err("ELF address normalization is not reversible".to_owned());
    }
    make_private_directory(&output.join("ida"))?;
    make_private_directory(&output.join("ida-work"))?;

    let binary_name = capture
        .binary
        .file_name()
        .ok_or_else(|| "archived binary has no file name".to_owned())?;
    let ida_input = output.join("ida-work").join(binary_name);
    std::fs::copy(&capture.binary, &ida_input).map_err(|error| {
        format!(
            "could not isolate archived binary {}: {error}",
            capture.binary.display()
        )
    })?;
    let mut permissions = ida_input
        .metadata()
        .map_err(|error| format!("could not stat isolated IDA input: {error}"))?
        .permissions();
    permissions.set_mode(permissions.mode() & !0o222);
    std::fs::set_permissions(&ida_input, permissions)
        .map_err(|error| format!("could not make IDA input read-only: {error}"))?;
    if hash::sha256_file(&ida_input)? != capture.binary_sha256 {
        return Err("isolated IDA input SHA-256 mismatch".to_owned());
    }

    output.write_new(
        "elf-load-segments.json",
        &elf_segments_json(&address_map, capture)?.to_python_json(),
    )?;
    run_stdout_file(
        Path::new("readelf"),
        &["-lW".to_owned(), capture.binary.display().to_string()],
        &output.join("readelf-program-headers.txt"),
        &output.join("readelf-program-headers.stderr"),
    )?;

    let bridge = output.join("ida-work/idalib-bridge.py");
    write_new(&bridge, IDALIB_BRIDGE.as_bytes())?;
    let dwarf = Tool::new("addr2line")
        .args([
            "-e".to_owned(),
            capture.binary.display().to_string(),
            "-f".to_owned(),
            "-C".to_owned(),
            "-i".to_owned(),
            format!("0x{requested:x}"),
        ])
        .probe()
        .map_err(|error| format!("addr2line could not start: {error}"))?;
    write_tool_capture(output, "dwarf.txt", "dwarf.stderr", &dwarf)?;
    if !dwarf.success() {
        return Err(format!(
            "addr2line failed with exit code {}",
            dwarf.code.unwrap_or(128)
        ));
    }

    let raw_result = output.join("ida-work/result.json");
    let idalib = Tool::new("timeout")
        .args([
            "-k".to_owned(),
            "5s".to_owned(),
            format!("{}s", plan.timeout_seconds),
            plan.idalib_python.display().to_string(),
            bridge.display().to_string(),
            ida_input.display().to_string(),
            format!("0x{requested:x}"),
            raw_result.display().to_string(),
        ])
        .probe()
        .map_err(|error| format!("IDALib could not start: {error}"))?;
    write_tool_capture(
        output,
        "ida-work/idalib.stdout",
        "ida-work/idalib.stderr",
        &idalib,
    )?;
    if !idalib.success() {
        return Err(format!(
            "IDALib failed with exit code {}; see {}",
            idalib.code.unwrap_or(128),
            output.join("ida-work/idalib.stderr").display()
        ));
    }
    regular_not_symlink(&raw_result, "IDALib bridge result")?;
    if hash::sha256_file(&ida_input)? != capture.binary_sha256 {
        return Err("isolated IDA input changed during analysis".to_owned());
    }
    let mut function = parse_idalib_result(&raw_result, requested)?;
    address_map.static_to_dso_offset(function.start)?;
    address_map.static_to_dso_offset(function.end - 1)?;
    write_ida_outputs(output, &function, capture, &ida_input, requested)?;

    run_stdout_file(
        Path::new("llvm-objdump"),
        &[
            "--disassemble".to_owned(),
            "--demangle".to_owned(),
            "--source".to_owned(),
            "--line-numbers".to_owned(),
            "-M".to_owned(),
            "intel".to_owned(),
            format!("--start-address=0x{:x}", function.start),
            format!("--stop-address=0x{:x}", function.end),
            capture.binary.display().to_string(),
        ],
        &output.join("llvm-disassembly.txt"),
        &output.join("llvm-disassembly.stderr"),
    )?;

    let expected_dso = binary_name
        .to_str()
        .ok_or_else(|| "archived binary file name is not UTF-8".to_owned())?;
    let buildids = Tool::new("perf")
        .args([
            "buildid-list".to_owned(),
            "-i".to_owned(),
            capture.perf_data.display().to_string(),
        ])
        .run()
        .map_err(|error| format!("perf buildid-list failed: {error}"))?;
    if !super::build_id_list_contains(&buildids.stdout, &capture.binary_build_id) {
        return Err(format!(
            "perf data does not contain binary Build ID {}",
            capture.binary_build_id
        ));
    }
    let perf_dso_path =
        build_id_dso_path(&buildids.stdout, &capture.binary_build_id, expected_dso)?;
    output.write_new("perf-buildids.txt", &buildids.stdout)?;

    run_stdout_file(
        Path::new("perf"),
        &[
            "script".to_owned(),
            "-G".to_owned(),
            "--no-demangle".to_owned(),
            "-i".to_owned(),
            capture.perf_data.display().to_string(),
            "-F".to_owned(),
            "hw:ip,dsoff,period,dso".to_owned(),
        ],
        &output.join("perf-script-events.txt"),
        &output.join("perf-script-events.stderr"),
    )?;
    let events = std::fs::read_to_string(output.join("perf-script-events.txt"))
        .map_err(|error| format!("could not read perf script events: {error}"))?;
    let (samples, selection_totals) =
        select_samples(&events, &perf_dso_path, &address_map, &function)?;
    let mut sample_text = format!(
        "# binary_sha256={}\n# binary_build_id={}\n# ida_function_name={}\n# perf_dso_path={}\n# normalization=perf-dso-file-offset-through-executable-elf-pt-load\n# fields=period runtime_ip dso_offset static_address raw_perf_row\n",
        capture.binary_sha256, capture.binary_build_id, function.name, perf_dso_path
    );
    for sample in &samples {
        let _ = writeln!(
            sample_text,
            "{}\t0x{:x}\t0x{:x}\t0x{:x}\t{}",
            sample.period,
            sample.runtime_ip,
            sample.dso_offset,
            sample.static_address,
            sample.source
        );
    }
    output.write_new("perf-function-samples.txt", &sample_text)?;
    let (totals, unmapped_percent) = aggregate(
        output,
        &mut function,
        &samples,
        &selection_totals,
        capture,
        &perf_dso_path,
        plan,
    )?;

    let metadata = Json::object([
        ("schemaVersion", Json::Int(3)),
        ("state", Json::string("COMPLETE")),
        ("label", Json::string(&plan.label)),
        (
            "addressNormalization",
            Json::object([
                (
                    "method",
                    Json::string("perf-dso-file-offset-through-executable-elf-pt-load"),
                ),
                (
                    "requestedDsoOffset",
                    Json::string(format!("0x{requested_dso_offset:x}")),
                ),
                (
                    "requestedStaticAddress",
                    Json::string(format!("0x{requested:x}")),
                ),
            ]),
        ),
        (
            "capture",
            Json::object([
                ("runId", Json::string(&capture.run_id)),
                (
                    "runDirectory",
                    Json::string(capture.root.display().to_string()),
                ),
                ("binary", Json::string(capture.binary.display().to_string())),
                ("binarySha256", Json::string(&capture.binary_sha256)),
                ("binaryBuildId", Json::string(&capture.binary_build_id)),
                (
                    "perfData",
                    Json::string(capture.perf_data.display().to_string()),
                ),
                (
                    "perfDataSha256",
                    Json::string(&capture.perf_data_sha256),
                ),
                ("perfDsoPath", Json::string(&perf_dso_path)),
            ]),
        ),
        (
            "idalib",
            Json::object([
                (
                    "python",
                    Json::string(plan.idalib_python.display().to_string()),
                ),
                ("bridgeSha256", Json::string(hash::sha256_file(&bridge)?)),
                (
                    "timeoutSeconds",
                    json_u64(plan.timeout_seconds, "IDALib timeout")?,
                ),
                ("boundary", Json::string("generated-direct-api-bridge")),
            ]),
        ),
        (
            "function",
            Json::object([
                ("name", Json::string(&function.name)),
                ("start", Json::string(format!("0x{:x}", function.start))),
                ("end", Json::string(format!("0x{:x}", function.end))),
            ]),
        ),
        ("selectionTotals", selection_totals_json(&selection_totals)?),
        ("totals", totals_json(&totals, unmapped_percent)?),
    ]);
    output.write_new("metadata.json", &metadata.to_python_json())?;

    let primary_files = [
        "metadata.json",
        "dwarf.txt",
        "dwarf.stderr",
        "elf-load-segments.json",
        "readelf-program-headers.txt",
        "readelf-program-headers.stderr",
        "ida/summary.json",
        "ida/disassembly.json",
        "ida/pseudocode.c",
        "ida-work/idalib-bridge.py",
        "ida-work/result.json",
        "ida-work/idalib.stdout",
        "ida-work/idalib.stderr",
        "llvm-disassembly.txt",
        "llvm-disassembly.stderr",
        "perf-buildids.txt",
        "perf-script-events.txt",
        "perf-script-events.stderr",
        "perf-function-samples.txt",
        "instruction-hotspots.json",
        "instruction-hotspots.tsv",
        "instruction-hotspots.txt",
    ];
    let mut sums = String::new();
    let mut file_rows = Vec::with_capacity(primary_files.len());
    for relative in primary_files {
        let digest = hash::sha256_file(&output.join(relative))?;
        let _ = writeln!(sums, "{digest}  {relative}");
        file_rows.push(Json::object([
            ("path", Json::string(relative)),
            ("sha256", Json::string(digest)),
        ]));
    }
    output.write_new("SHA256SUMS", &sums)?;
    let contract = Json::object([
        ("schemaVersion", Json::Int(1)),
        ("state", Json::string("COMPLETE")),
        ("collector", Json::string("perf-hotspot-bundle")),
        ("runId", Json::string(&capture.run_id)),
        ("label", Json::string(&plan.label)),
        ("binarySha256", Json::string(&capture.binary_sha256)),
        ("binaryBuildId", Json::string(&capture.binary_build_id)),
        ("files", Json::Array(file_rows)),
        (
            "sha256sumsSha256",
            Json::string(hash::sha256_file(&output.join("SHA256SUMS"))?),
        ),
    ]);
    output.write_new("bundle-contract.json", &contract.to_python_json())?;
    publication::publish_success_marker(
        &output.join("bundle-completion.json"),
        &output.join("bundle-contract.json"),
        &format!("{}:{}", capture.run_id, plan.label),
        "perf-hotspot-bundle",
    )?;
    Ok(())
}

/// Exports and publishes one instruction-level hotspot bundle.
///
/// # Errors
///
/// Returns an argument, capture-identity, external-mechanism, mapping-gate or
/// publication diagnostic. Once created, an incomplete output is marked
/// `FAILED` and is never silently reused.
pub fn run(plan: &Plan) -> Result<String, String> {
    validate(plan)?;
    for program in ["addr2line", "llvm-objdump", "perf", "readelf", "timeout"] {
        if !Tool::exists(program) {
            return Err(format!("required tool unavailable: {program}"));
        }
    }
    let capture = load_capture(plan)?;
    let hotspots = capture.root.join("hotspots");
    match hotspots.symlink_metadata() {
        Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_dir() => {
            return Err(format!(
                "hotspots path is not a non-symlink directory: {}",
                hotspots.display()
            ));
        }
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            make_private_directory(&hotspots)?;
        }
        Err(error) => {
            return Err(format!("could not inspect {}: {error}", hotspots.display()));
        }
    }
    let hotspot = hotspots.join(&plan.label);
    let output = RunDirectory::create(&hotspot)?;
    if let Err(error) = execute(plan, &capture, &output) {
        let failure = Json::object([
            ("schemaVersion", Json::Int(2)),
            ("state", Json::string("FAILED")),
            ("label", Json::string(&plan.label)),
            ("error", Json::string(&error)),
        ]);
        let _ = output.write_new("FAILED.json", &failure.to_python_json());
        return Err(error);
    }
    Ok(format!("hotspot bundle complete: {}", hotspot.display()))
}

